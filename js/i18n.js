// UI language.
//
// Two separate things travel under the word "language" here, and keeping
// them apart matters:
//
//   the INTERFACE language  a personal setting, stored in this browser, that
//                           decides what the buttons say. Yours alone -- two
//                           people in the same room can read the game in two
//                           different languages.
//   the WORD language       a property of the ROOM (wf_rooms.lang), fixed by
//                           whoever created it, deciding which pool secrets
//                           come from. Everyone at one table must be guessing
//                           the same word, so a joiner inherits it.
//
// Creating a room sends the interface language as the word language, because
// that is what someone means when they pick Italian on the title screen. But
// joining a room does not change your interface: you read the menus in your
// language and guess in the room's.
//
// A missing key falls back to English rather than rendering blank, and an
// unknown key renders as itself -- a visible key is a bug report; an empty
// button is a mystery.

