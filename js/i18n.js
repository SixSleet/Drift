/** Ordinals for the lockdown message, per language. */
const ORDINALS = {
  en: ['1st', '2nd', '3rd', '4th', '5th', '6th', '7th'],
  it: ['1ª', '2ª', '3ª', '4ª', '5ª', '6ª', '7ª'],
  de: ['1.', '2.', '3.', '4.', '5.', '6.', '7.'],
  es: ['1ª', '2ª', '3ª', '4ª', '5ª', '6ª', '7ª'],
  fr: ['1re', '2e', '3e', '4e', '5e', '6e', '7e'],
};

function detect() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (isLanguage(saved)) return saved;
  } catch { /* private mode: fall through to the browser's own setting */ }
  for (const tag of navigator.languages ?? [navigator.language ?? 'en']) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (isLanguage(code)) return code;
  }
  return 'en';
}

let current = detect();

export function getLang() { return current; }

export function setLang(code) {
  if (!isLanguage(code) || code === current) return current;
  current = code;
  try { localStorage.setItem(STORE_KEY, code); } catch { /* not fatal */ }
  document.documentElement.lang = code;
  // The event is the only notification: main.js listens for it and repaints
  // both the static strings and everything derived from them, so doing half
  // of that here as well would only mean two passes over the same DOM.
  window.dispatchEvent(new CustomEvent('wf-lang', { detail: { lang: code } }));
  return current;
}

/**
 * Look up a string. `{name}` placeholders are filled from `vars`.
 *
 * English is the fallback for a key a translation has not covered, and the
 * key itself is the fallback for one nobody has: a visible `toast.whatever`
 * on screen is a bug report, where an empty string is a mystery.
 */
export function t(key, vars) {
  const raw = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

/**
 * A round event's name, card text and mid-round line.
 *
 * config.js still carries each event's emoji, tint and fx -- those are
 * presentation, not language -- but every word came out of it and lives
 * here instead, keyed by the event name the server sends.
 */
export const eventLabel = (name) => t(`event.${name}.label`);
export const eventBlurb = (name) => t(`event.${name}.blurb`);
export const eventMid = (name) => t(`event.${name}.mid`);

/** A mode's name and its one-line pitch on the title screen. */
export const modeLabel = (mode) => t(`mode.${mode}`);
export const modeBlurb = (mode) => t(`mode.${mode}.blurb`);

/** The localised ordinal used by lockdown's "the 3rd letter has to be N". */
export function ordinal(i) {
  return (ORDINALS[current] ?? ORDINALS.en)[i] ?? `${i + 1}.`;
}

/**
 * Rewrites everything in the document carrying a translation attribute:
 *
 *   data-i18n            textContent
 *   data-i18n-html       innerHTML, for the few strings with markup in them
 *   data-i18n-aria       aria-label
 *   data-i18n-placeholder placeholder
 *
 * Called on boot and on every language change, so it must be idempotent --
 * it only ever writes derived values, never reads the DOM as state.
 */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
}

/** Exposed for the test harness: which keys a language is missing. */
export function __missingKeys(code) {
  const base = Object.keys(STRINGS.en);
  return base.filter((k) => !(k in (STRINGS[code] ?? {})));
}
export const __strings = STRINGS;
